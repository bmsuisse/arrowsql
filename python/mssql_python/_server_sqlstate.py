# msodbcsql severity tiers for unmapped errors: > 18 -> HY000, > 10 -> 42000, else 01000.
_SEVERITY_MAX_INFO = 10
_SEVERITY_MAX_USER = 18


def sqlstate_for_server_error(number: int, severity: Optional[int] = None) -> str:
    """Return the SQLSTATE msodbcsql reports for a SQL Server error number."""
    mapped = _SERVER_ERROR_TO_SQLSTATE.get(number)
    if mapped is not None:
        return mapped
    if severity is None or severity > _SEVERITY_MAX_USER:
        return "HY000"
    if severity > _SEVERITY_MAX_INFO:
        return "42000"
    return "01000"
